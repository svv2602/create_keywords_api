#!/usr/bin/env ruby
# Тестовый скрипт для проверки ограничения длины отзыва

require_relative 'config/environment'

puts "="*80
puts "ТЕСТИРОВАНИЕ ОГРАНИЧЕНИЯ ДЛИНЫ ОТЗЫВА (1000 символов)"
puts "="*80
puts

# Создаем очень длинный отзыв (превышает 1100 символов - порог с 10% толерантностью)
long_review = <<~REVIEW
  Приобрел эти шины для своей машины несколько месяцев назад и хочу поделиться своим опытом использования.
  В целом впечатления положительные, но есть некоторые моменты которые хотелось бы отметить.

  Начну с положительных моментов. Управляемость на сухой дороге просто отличная - машина слушается руля,
  входит в повороты уверенно, не сносит. Курсовая устойчивость тоже на высоте, даже на высоких скоростях
  автомобиль держит траекторию без проблем. Разгон и торможение стали лучше чем на предыдущих шинах.

  На мокрой дороге тоже все неплохо - сцепление достаточное, машину не заносит, аквапланирования не заметил
  даже в сильный дождь. Правда нужно быть аккуратнее в лужах на скорости, но это нормально для любых шин.

  Что касается износостойкости, то пока проехал около 15000 километров и износ минимальный, протектор
  практически как новый. Думаю что этих шин хватит на несколько сезонов точно, что очень радует учитывая
  их стоимость. Комфорт езды тоже на приличном уровне - шины не шумные, вибрации нет, подвеска отрабатывает
  неровности хорошо.

  Из минусов могу отметить разве что немного повышенный расход топлива по сравнению с предыдущими шинами,
  но разница небольшая примерно 0.3-0.5 литра на сто километров. Также цена немного кусается, но качество
  того стоит. В общем рекомендую к покупке всем кто ищет надежные шины с хорошими характеристиками.
REVIEW

puts "Длина оригинального отзыва: #{long_review.length} символов"
puts "Лимит: 1000 символов"
puts "Лимит с толерантностью 10%: 1100 символов"
puts "Превышение: #{long_review.length > 1100 ? 'ДА' : 'НЕТ'}"
puts "-"*80
puts

# Контекст для обработки
context = {
  brand: "Michelin",
  model: "Pilot Sport 4",
  gender: "мужчина",
  grade: 4.0,
  array_average: [4.0, 4.5, 3.5, 4.0]
}

processor = UniversalReviewProcessor.new

puts "ТЕСТ 1: Проверка метода check_and_shorten_if_needed"
puts "-"*80

# Тестируем метод напрямую
result = processor.send(:check_and_shorten_if_needed, long_review, context)

puts "Длина результата: #{result.length} символов"
puts "Уложились в лимит: #{result.length <= 1100 ? 'ДА ✓' : 'НЕТ ✗'}"
puts "\nРезультат:"
puts result
puts

puts "="*80
puts "ТЕСТ 2: Проверка build_shorten_prompt"
puts "-"*80

shorten_prompt = processor.send(:build_shorten_prompt, long_review, context, 1000)
puts shorten_prompt
puts

puts "="*80
puts "ТЕСТ 3: Проверка truncate_review_safely"
puts "-"*80

# Тестируем безопасную обрезку
truncated = processor.send(:truncate_review_safely, long_review, 1000)
puts "Длина обрезанного: #{truncated.length} символов"
puts "Текст:"
puts truncated
puts

puts "="*80
puts "ТЕСТ 4: Проверка коротких отзывов (не должны обрабатываться)"
puts "-"*80

short_review = "Отличные шины! Проехал 10000 км, доволен. Рекомендую."
puts "Длина короткого отзыва: #{short_review.length} символов"

result_short = processor.send(:check_and_shorten_if_needed, short_review, context)
puts "Отзыв изменился: #{result_short == short_review ? 'НЕТ ✓ (правильно)' : 'ДА ✗ (ошибка!)'}"
puts

puts "="*80
puts "ТЕСТ 5: Отзыв на границе (ровно 1100 символов)"
puts "-"*80

# Создаем отзыв ровно 1100 символов
boundary_review = "А" * 1100
puts "Длина граничного отзыва: #{boundary_review.length} символов"

result_boundary = processor.send(:check_and_shorten_if_needed, boundary_review, context)
puts "Отзыв изменился: #{result_boundary != boundary_review ? 'ДА (правильно - на границе срабатывает)' : 'НЕТ'}"
puts "Длина результата: #{result_boundary.length} символов"
puts

puts "="*80
puts "ТЕСТИРОВАНИЕ ЗАВЕРШЕНО"
puts "="*80
puts "\nДля полноценного теста с реальным AI запустите:"
puts "  rails runner test_review_length_limit.rb"
puts "\nПримечание: Для полной проверки нужен доступ к DeepSeek API"

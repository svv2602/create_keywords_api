# app/services/car_seo_text_generator.rb
class CarSeoTextGenerator
  include StringProcessing

  def initialize(params)
    @brand = params[:brand]
    @model = params[:model]
    @language = params[:language] || 'ru'
    @typical_sizes = params[:typical_sizes] || []
    @generation = params[:generation]
    @production_years = params[:production_years]
    @body_type = params[:body_type]
    @car_class = params[:car_class]
  end

  def generate
    validate_params!

    prompt = build_prompt

    # Генерация текста через AI
    response = ContentWriter.new.write_seo_text(prompt, 3500)

    if response
      text = response['choices'][0]['message']['content'].strip
      {
        text: text,
        brand: @brand,
        model: @model,
        language: @language,
        generated_at: Time.current
      }
    else
      { error: 'Failed to generate text' }
    end
  rescue => e
    { error: e.message }
  end

  private

  def validate_params!
    raise ArgumentError, 'Brand is required' if @brand.blank?
    raise ArgumentError, 'Model is required' if @model.blank?
    raise ArgumentError, 'Language must be ru or ua' unless %w[ru ua].include?(@language)
    raise ArgumentError, 'Typical sizes are required' if @typical_sizes.blank?
  end

  def build_prompt
    @language == 'ru' ? build_russian_prompt : build_ukrainian_prompt
  end

  def build_russian_prompt
    prompt = <<~PROMPT
      Напиши SEO-оптимизированный текст для страницы подбора шин для автомобиля #{@brand.capitalize} #{@model.capitalize}.

      ИСХОДНЫЕ ДАННЫЕ:
      - Марка: #{@brand.capitalize}
      - Модель: #{@model.capitalize}
      #{@generation.present? ? "- Поколение: #{@generation}" : ""}
      #{@production_years.present? ? "- Годы выпуска: #{@production_years}" : ""}
      #{@body_type.present? ? "- Тип кузова: #{@body_type}" : ""}
      #{@car_class.present? ? "- Класс автомобиля: #{@car_class}" : ""}
      - Типичные размеры шин: #{@typical_sizes.join(', ')}

      ОБЯЗАТЕЛЬНЫЕ ТРЕБОВАНИЯ:

      Структура текста:

      1. Вступление (2-3 предложения):
         - Упомяните "шины для #{@brand.capitalize} #{@model.capitalize}"
         #{@body_type.present? ? "- Укажите тип кузова: #{@body_type}" : "- Если можешь определить тип кузова по марке и модели, укажи его"}
         - Подчеркните, что это подбор по заводским параметрам

      Пример вступления:
      "Если вы ищете подходящие шины для #{@brand.capitalize} #{@model.capitalize}, на этой странице вы найдете варианты, идеально подходящие по размеру, сезону и стилю вождения.#{@body_type.present? ? " Этот #{@body_type}" : " Этот автомобиль"} требует качественных шин, которые обеспечат комфорт и безопасность."

      2. Основная часть (3-4 абзаца):
         - Опишите типичные размеры шин для этой модели: #{@typical_sizes.join(', ')}
         - Укажите варианты сезонности (летние, зимние, всесезонные)
         - Упомяните популярные бренды для #{@car_class.present? ? "#{@car_class}-класса" : "этой модели"}
         - Добавьте советы по выбору: индексы нагрузки/скорости, рекомендуемое давление

      3. Преимущества подбора на сайте ProKoleso (2-3 предложения):
         - Удобные фильтры по параметрам
         - Доставка, удобные формы оплаты и профессиональная консультация
         - Только проверенные бренды с гарантией

      4. Заключение с призывом к действию (1-2 предложения):
         - Призыв выбрать шины в каталоге и оформить заказ онлайн

      КЛЮЧЕВЫЕ СЛОВА (использовать по одному разу каждое):
      - "Купить шины на #{@brand.capitalize} #{@model.capitalize}"
      - "Купить резину на #{@brand.capitalize} #{@model.capitalize}"

      ВАЖНЫЕ ПРАВИЛА:
      - Объем текста: 1500-2500 знаков (для популярных моделей можно до 3000)
      - Естественный стиль изложения, избегать рекламных штампов
      - Не использовать личные местоимения в единственном числе (я, мой)
      - Избегать местоимений "их", "njih", "его", "ее"
      - Каждое предложение должно быть самостоятельным по смыслу
      - Тошнотность текста не больше 20%, водность не больше 60%
      - Предложения должны быть простыми и понятными

      ВАЖНО ПО ССЫЛКАМ:
      - Если упоминаешь размеры с ссылками, используй формат: /shiny/w-215/h-55/r-17/
      - ВСЕГДА используй дефис после w-, h-, r- и слэш между параметрами
      - НЕПРАВИЛЬНО: /shiny/215/55/r17/ или /shiny/w215/h55/r-17/
      - ПРАВИЛЬНО: /shiny/w-215/h-55/r-17/

      Примеры построения предложений:
      - Неправильно: "ProKoleso - это надежный партнер. Поэтому мы предлагаем лучшее"
      - Правильно: "ProKoleso - надежный партнер для всех автовладельцев. Мы предлагаем лучшие решения для вашего автомобиля"

      - Неправильно: "Yokohama - компания с отличными технологиями. Их продукция популярна"
      - Правильно: "Yokohama славится передовыми технологиями. Продукция компании пользуется популярностью"
    PROMPT

    prompt
  end

  def build_ukrainian_prompt
    # Перевод значений для украинского языка
    body_type_ua = translate_body_type(@body_type) if @body_type.present?

    prompt = <<~PROMPT
      Напиши SEO-оптимізований текст для сторінки підбору шин для автомобіля #{@brand.capitalize} #{@model.capitalize}.

      ВИХІДНІ ДАНІ:
      - Марка: #{@brand.capitalize}
      - Модель: #{@model.capitalize}
      #{@generation.present? ? "- Покоління: #{@generation}" : ""}
      #{@production_years.present? ? "- Роки випуску: #{@production_years}" : ""}
      #{body_type_ua.present? ? "- Тип кузова: #{body_type_ua}" : ""}
      #{@car_class.present? ? "- Клас автомобіля: #{@car_class}" : ""}
      - Типові розміри шин: #{@typical_sizes.join(', ')}

      ОБОВ'ЯЗКОВІ ВИМОГИ:

      Структура тексту:

      1. Вступ (2-3 речення):
         - Згадайте "шини для #{@brand.capitalize} #{@model.capitalize}"
         #{body_type_ua.present? ? "- Вкажіть тип кузова: #{body_type_ua}" : "- Якщо можеш визначити тип кузова за маркою та моделлю, вкажи його"}
         - Підкресліть, що це підбір за заводськими параметрами

      Приклад вступу:
      "Якщо ви шукаєте відповідні шини для #{@brand.capitalize} #{@model.capitalize}, на цій сторінці ви знайдете варіанти, ідеально підходящі за розміром, сезоном та стилем водіння.#{body_type_ua.present? ? " Цей #{body_type_ua}" : " Цей автомобіль"} потребує якісних шин, які забезпечать комфорт та безпеку."

      2. Основна частина (3-4 абзаци):
         - Опишіть типові розміри шин для цієї моделі: #{@typical_sizes.join(', ')}
         - Вкажіть варіанти сезонності (літні, зимові, всесезонні)
         - Згадайте популярні бренди для #{@car_class.present? ? "#{@car_class}-класу" : "цієї моделі"}
         - Додайте поради щодо вибору: індекси навантаження/швидкості, рекомендований тиск

      3. Переваги підбору на сайті ProKoleso (2-3 речення):
         - Зручні фільтри за параметрами
         - Доставка, зручні форми оплати та професійна консультація
         - Тільки перевірені бренди з гарантією

      4. Висновок із закликом до дії (1-2 речення):
         - Заклик обрати шини в каталозі та оформити замовлення онлайн

      КЛЮЧОВІ СЛОВА (використовувати по одному разу кожне):
      - "Купити шини на #{@brand.capitalize} #{@model.capitalize}"
      - "Купити резину на #{@brand.capitalize} #{@model.capitalize}"

      ВАЖЛИВІ ПРАВИЛА:
      - Обсяг тексту: 1500-2500 знаків (для популярних моделей можна до 3000)
      - Природний стиль викладу, уникати рекламних штампів
      - Не використовувати особові займенники в однині (я, мій)
      - Уникати займенників "їх", "них", "його", "її"
      - Кожне речення має бути самостійним за змістом
      - Тошнотність тексту не більше 20%, водність не більше 60%
      - Речення мають бути простими та зрозумілими

      ВАЖЛИВО ПО ПОСИЛАННЯМ:
      - Якщо згадуєш розміри з посиланнями, використовуй формат: /shiny/w-215/h-55/r-17/
      - ЗАВЖДИ використовуй дефіс після w-, h-, r- та слеш між параметрами
      - НЕПРАВИЛЬНО: /shiny/215/55/r17/ або /shiny/w215/h55/r-17/
      - ПРАВИЛЬНО: /shiny/w-215/h-55/r-17/

      Приклади побудови речень:
      - Неправильно: "ProKoleso - це надійний партнер. Тому ми пропонуємо найкраще"
      - Правильно: "ProKoleso - надійний партнер для всіх автовласників. Ми пропонуємо найкращі рішення для вашого автомобіля"

      - Неправильно: "Yokohama - компанія з відмінними технологіями. Їхня продукція популярна"
      - Правильно: "Yokohama славиться передовими технологіями. Продукція компанії користується популярністю"
    PROMPT

    prompt
  end

  def translate_body_type(body_type)
    translations = {
      'седан' => 'седан',
      'хэтчбек' => 'хетчбек',
      'кроссовер' => 'кросовер',
      'внедорожник' => 'позашляховик',
      'универсал' => 'універсал',
      'купе' => 'купе',
      'минивэн' => 'мінівен',
      'пикап' => 'пікап'
    }
    translations[body_type.downcase] || body_type
  end
end
